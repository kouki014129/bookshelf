<?php

namespace Database\Seeders;

use App\Models\Book;
use App\Models\Review;
use App\Models\User;
use Illuminate\Database\Seeder;

class ReviewSeeder extends Seeder
{
    public function run(): void
    {
        $users = User::orderBy('id')->take(5)->get();
        $books = Book::orderBy('id')->take(11)->get();

        $comments = [
            '読みやすく、内容も非常に分かりやすかったです。',
            '実践的な内容が多く、すぐに活用できそうです。',
            '説明が丁寧で、初心者にも理解しやすい一冊でした。',
            '具体例が豊富で、最後まで楽しく読めました。',
            '考え方を見直すきっかけになりました。',
            '内容が充実していて、何度も読み返したいです。',
            '専門的な内容ですが、分かりやすく整理されています。',
            '期待していた以上に学びの多い本でした。',
            '文章が読みやすく、短期間で読み終えられました。',
            '仕事や日常生活に役立つ内容が多かったです。',
            '重要なポイントが簡潔にまとめられています。',
            '初心者だけでなく、経験者にもおすすめできます。',
            '少し難しい部分もありましたが、勉強になりました。',
            '具体的な事例があり、内容をイメージしやすかったです。',
            '著者の考え方に共感できる部分が多くありました。',
            '繰り返し読むことで、さらに理解が深まりそうです。',
            '基礎から応用まで幅広く学べる内容でした。',
            'テンポよく読めて、内容にも満足しています。',
            '新しい知識や視点を得ることができました。',
            '友人にも勧めたいと思える一冊です。',
            '説明が論理的で、内容を整理しやすかったです。',
            '実務で使える知識が多く掲載されています。',
            '読み終えた後に行動したくなる内容でした。',
            '難しいテーマを身近な言葉で説明しています。',
            '初心者の最初の一冊として適していると思います。',
            '内容が具体的で、理解しやすかったです。',
            '期待どおりの内容で、満足できました。',
            '何度も確認したくなる重要な内容が多かったです。',
            '著者の経験が反映された説得力のある内容でした。',
            '全体的にバランスよく構成されていました。',
            '知識を整理するために役立つ一冊でした。',
            '読んでよかったと思える内容でした。',
        ];

        $reviewNumber = 0;

        /*
         * 各書籍に登録するレビュー件数。
         * 合計32件です。
         */
        $reviewCounts = [
            3, 3, 3, 3, 3, 3,
            3, 3, 3, 3, 2,
        ];

        foreach ($books as $bookIndex => $book) {
            $count = $reviewCounts[$bookIndex];

            for ($i = 0; $i < $count; $i++) {
                /*
                 * 同じユーザーが同じ本に重複してレビューしないように、
                 * 書籍ごとに開始ユーザーをずらします。
                 */
                $user = $users[($bookIndex + $i) % $users->count()];

                Review::updateOrCreate(
                    [
                        'user_id' => $user->id,
                        'book_id' => $book->id,
                    ],
                    [
                        'rating' => 3 + (($bookIndex + $i) % 3),
                        'comment' => $comments[$reviewNumber],
                    ]
                );

                $reviewNumber++;
            }
        }
    }
}